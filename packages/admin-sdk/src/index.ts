import createClient, { type Client } from "openapi-fetch";
import type { paths, components } from "./types.gen.js"; // generated by openapi-typescript

export class AdminClient {
  accessToken: string | undefined;
  client: Client<paths>;

  constructor(baseUrl: string) {
    this.client = createClient({ baseUrl });
  }


  async signIn(credentials: components["schemas"]["SignInDto"]) {
    const { data } = await this.client.POST("/auth/signin", {
      body: credentials,
    })
    return data?.access_token
  }

  async refreshAccessToken() {
    const { data } = await this.client.GET("/auth/token/refresh", {
      credentials: "include",
    });
    this.accessToken = data?.access_token
    return this.accessToken
  }

  // request is a thunk so the retry rebuilds headers off the refreshed accessToken, not a stale one
  private async do<T>(
    request: () => Promise<{ data?: T; error?: unknown; response: Response }>,
  ) {
    const result = await request();
    if (result.response.status === 401) {
      await this.refreshAccessToken();
      return await request();
    }
    return result;
  }

  products = {
    list: async () => {
      const {data} = await this.do(() =>
        this.client.GET("/products", {
          credentials: "include",
          headers: {
            Authorization: `Bearer ${this.accessToken}`,
          },
        }),
      )
      return data
    }
  }
}
